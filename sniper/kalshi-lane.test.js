'use strict';
const assert = require('assert');
const { computeBorrow, borrowConfig } = require('./kalshi-lane');
const { createLimiter } = require('./limiter');
const cfg = borrowConfig({ SNIPER_KALSHI_BORROW: '1' });
const now = Date.parse('2026-10-26T12:00:10Z');
const lane = (o) => ({ ts: '2026-10-26T12:00:09Z', active_locks: 0, writes_10s: 0, ...o });
let r;
r = computeBorrow({ lane: lane(), now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 8);
r = computeBorrow({ lane: lane(), now, reserved: 9, cfg: borrowConfig({}) }); assert.strictEqual(r.borrow, 0);
r = computeBorrow({ lane: null, now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 0);
r = computeBorrow({ lane: lane({ ts: '2026-10-26T12:00:00Z' }), now, reserved: 9, cfg }); assert.strictEqual(r.why, 'stale');
r = computeBorrow({ lane: lane({ active_locks: 4 }), now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 0);
r = computeBorrow({ lane: lane({ active_locks: 2, writes_10s: 10 }), now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 5);
r = computeBorrow({ lane: lane({ writes_10s: 30 }), now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 0);
r = computeBorrow({ lane: lane(), now, reserved: 9, cfg, cooldownUntil: now + 1 }); assert.strictEqual(r.why, '429_cooldown');
r = computeBorrow({ lane: lane({ active_locks: 'x' }), now, reserved: 9, cfg }); assert.strictEqual(r.borrow, 0);
const l = createLimiter({ name: 't', ratePerSec: 6, ratePerSecOn429: 4, burst: 5 });
assert.strictEqual(l.setRate(14), 14); l.on429(); assert.strictEqual(l.stats().ratePerSec, 4); assert.strictEqual(l.setRate(14), 4);
console.log('kalshi-lane ok');
